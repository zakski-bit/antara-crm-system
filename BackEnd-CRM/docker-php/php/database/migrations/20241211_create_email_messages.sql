CREATE TABLE IF NOT EXISTS `email_messages` (
    `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
    `folder` VARCHAR(50) NOT NULL DEFAULT 'inbox',
    `subject` VARCHAR(255) NOT NULL,
    `snippet` VARCHAR(255) NOT NULL,
    `body_html` MEDIUMTEXT NOT NULL,
    `body_text` TEXT NOT NULL,
    `sender_name` VARCHAR(255) DEFAULT NULL,
    `sender_email` VARCHAR(255) NOT NULL,
    `to_addresses` TEXT NOT NULL,
    `cc_addresses` TEXT DEFAULT NULL,
    `is_read` TINYINT(1) NOT NULL DEFAULT 0,
    `is_starred` TINYINT(1) NOT NULL DEFAULT 0,
    `has_attachments` TINYINT(1) NOT NULL DEFAULT 0,
    `received_at` DATETIME DEFAULT NULL,
    `created_at` DATETIME NOT NULL,
    `updated_at` DATETIME NOT NULL,
    PRIMARY KEY (`id`),
    INDEX `email_messages_folder_index` (`folder`),
    INDEX `email_messages_received_at_index` (`received_at`),
    INDEX `email_messages_starred_index` (`is_starred`),
    INDEX `email_messages_read_index` (`is_read`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

